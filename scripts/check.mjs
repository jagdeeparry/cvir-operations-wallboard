import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const files = ['public/index.html','public/styles.css','public/app.js','src/worker.js','.openai/hosting.json'];
for (const file of files) await readFile(new URL('../' + file, import.meta.url), 'utf8');
const app = await readFile(new URL('../public/app.js', import.meta.url), 'utf8');
const worker = await readFile(new URL('../src/worker.js', import.meta.url), 'utf8');
new vm.Script(app);
const { durationSeconds } = await import(new URL('../src/worker.js', import.meta.url));
assert.equal(durationSeconds(7200), 7200);
assert.equal(durationSeconds('86400'), 86400);
assert.equal(durationSeconds(''), null);
assert.equal(durationSeconds({}), null);
assert.equal(durationSeconds({ value: '10800' }), 10800);
assert.equal(durationSeconds({ seconds: 14400 }), 14400);
assert.equal(durationSeconds({ completedCycles: [{ elapsedTime: { millis: 7200000 } }] }), 7200);
assert.match(worker, /status CHANGED TO "In Review" AFTER startOfDay\(\)/);
assert.match(worker, /uniqueIssues\(\[doneToday\.issues, rcaToday\.issues, inReviewToday\.issues\]\)/);
assert.match(worker, /Darshita: '712020:c8cf55cc-36d0-41a2-936e-be1b0946dadf'/);
assert.match(worker, /status IN ' \+ ACTIVE_ASSIGNED_STATUSES/);
assert.match(worker, /normalize\(x\.creator\) === normalize\(DRISHTI_CREATOR\)/);
assert.match(worker, /api\.atlassian\.com\/ex\/jira/);
assert.match(worker, /'Bearer ' \+ env\.JIRA_API_TOKEN/);
assert.match(app, /Closed \/ In Review today/);
assert.match(app, /renderMttrGroup\('operational'/);
assert.match(app, /renderMttrGroup\('drishti'/);
assert.match(app, /cvir-seen-sev1-keys-v1/);
assert.match(app, /handleNewSev1\(data\)/);
assert.match(app, /setInterval\(alarmBurst, 3600\)/);
assert.match(app, /setTimeout\(stopSev1Alarm, 60000\)/);
assert.match(app, /sevAlertAcknowledge/);
JSON.parse(await readFile(new URL('../.openai/hosting.json', import.meta.url), 'utf8'));
console.log('Source files and browser JavaScript validated');
